#!/usr/bin/env node
/** Resource-owned References, previews, browser history and overflowing tabs. */
import { chromium, expect } from '@playwright/test'
import { mkdirSync } from 'node:fs'
import { join } from 'node:path'

const origin = process.argv[2]
if (!origin) throw new Error('Pass a running fixture-shop report URL.')
const report = await fetch(new URL('/_businesslens/report.json', origin)).then(response => response.json())
const screenshots = process.env.BLR_NAV_SCREENSHOTS
if (screenshots) mkdirSync(screenshots, { recursive: true })
const browser = await chromium.launch()
const errors = []
const urlValue = (page, key) => new URL(page.url()).searchParams.get(key)
const capture = async (page, name) => { if (screenshots) await page.screenshot({ path: join(screenshots, name), animations: 'disabled' }) }
const attachments = report => [...report.references, ...Object.values(report.model)
  .filter(Array.isArray).flat().flatMap(resource => resource.references ?? [])]
const attachmentCount = report => attachments(report).length
const externalCount = report => attachments(report).filter(reference => /^https?:\/\//i.test(reference.target)).length

async function activeTabFits(panel) {
  await expect.poll(() => panel.locator('[role="tablist"]').evaluate(list => {
    const tab = list.querySelector('[aria-selected="true"]')
    const bounds = list.getBoundingClientRect()
    const active = tab.getBoundingClientRect()
    return active.left >= bounds.left - 1 && active.right <= bounds.right + 1
  })).toBe(true)
}

try {
  for (const width of [1440, 390, 320]) {
    const context = await browser.newContext({ viewport: { width, height: 900 }, reducedMotion: 'reduce' })
    const page = await context.newPage()
    page.on('pageerror', error => errors.push(error.message))
    const panel = page.locator('[data-resource-panel]')
    const references = panel.locator('[data-resource-references]')
    const catalog = page.locator('[data-reference-catalog]')

    // The Product's inventory is read by where references point: one row per
    // path or link, its citations behind the row, and one card per kind.
    await page.goto(`${origin}/?t=references`)
    await expect(catalog.getByRole('region', { name: 'In this repository', exact: true })).toBeVisible()
    // Every kind the format defines has a card; one the model does not use reads zero.
    const kinds = new Set(attachments(report).map(reference => reference.kind))
    await expect(catalog.locator('[data-reference-summary]')).toHaveCount(8)
    for (const kind of ['code', 'doc', 'spec', 'prd', 'proposal', 'adr', 'visual', 'research'].filter(kind => !kinds.has(kind))) {
      await expect(catalog.locator(`[data-reference-summary="${kind}"] [data-reference-summary-count]`)).toHaveText('0')
    }
    const locations = new Set(attachments(report).filter(reference => !/^https?:/.test(reference.target))
      .map(reference => reference.target.split('#')[0].replace(/:\d+(?:-\d+)?$/, '').replace(/\/$/, '')))
    await expect(catalog.locator('[data-reference-reveal]')).toHaveCount(locations.size + new Set(attachments(report)
      .filter(reference => /^https?:/.test(reference.target)).map(reference => reference.target.split('#')[0])).size)
    // Neither generator nor schema details are printed, in the header or after the last reading.
    await expect(page.getByText(/^Generated by /)).toHaveCount(0)
    await expect(page.locator('[data-report-status]')).not.toContainText(report.schemaVersion)
    await expect(catalog.locator('[data-reference-target]')).toHaveCount(0)
    await catalog.getByRole('button', { name: 'Expand all', exact: true }).click()
    await expect(catalog.locator('[data-reference-target]')).toHaveCount(attachmentCount(report))
    await catalog.getByRole('button', { name: 'Collapse all', exact: true }).click()
    await expect(catalog.locator('[data-reference-target]')).toHaveCount(0)
    await page.reload()
    await expect(catalog.locator('[data-reference-target]')).toHaveCount(0)
    await catalog.getByRole('button', { name: 'Expand all', exact: true }).click()
    await expect(catalog.locator('[data-reference-target]')).toHaveCount(attachmentCount(report))
    const owner = catalog.locator('a[data-resource-key="capability:browse-catalog"]')
    const ownerUrl = new URL(await owner.getAttribute('href'), page.url())
    expect(ownerUrl.searchParams.get('t')).toBe('references')
    expect(ownerUrl.searchParams.get('rt')).toBe('references')
    await owner.press('Enter')
    await expect(panel.locator('[data-resource-heading]')).toHaveText('Catalog browsing')
    await expect(references.locator('[data-reference-target]')).toHaveCount(1)
    await expect.poll(() => urlValue(page, 'rt')).toBe('references')
    await page.reload()
    await expect(references).toBeVisible()
    await panel.getByRole('button', { name: 'Close resource', exact: true }).click()
    await expect.poll(() => urlValue(page, 'e')).toBeNull()
    await expect.poll(() => urlValue(page, 't')).toBe('references')
    await catalog.locator('a[data-resource-key="capability-scenario:browse-catalog"]').first().click()
    await expect(panel.locator('[data-resource-heading]')).toHaveText('Browse the catalog')
    await expect(references.locator('[data-reference-target]')).toHaveCount(2)
    await expect.poll(() => urlValue(page, 'e')).toBe('capability-scenario:browse-catalog')
    await page.goBack()
    await expect(panel).toHaveCount(0)
    await catalog.getByRole('button', { name: 'Collapse src', exact: true }).click()
    await page.reload()
    await expect(catalog.getByRole('button', { name: 'Expand src', exact: true })).toBeVisible()
    // A closed folder names what opening it would find, as a way in.
    await expect(catalog.locator('[data-reference-inside]').first()).toBeVisible()
    await page.goto(ownerUrl.href)
    await expect(references.locator('[data-reference-target]')).toHaveCount(1)
    await panel.getByRole('button', { name: 'Close resource', exact: true }).click()
    await expect(catalog.getByRole('button', { name: 'Expand src', exact: true })).toBeVisible()
    await catalog.getByRole('button', { name: 'Expand src', exact: true }).click()
    // Search finds paths by name and opens the folders above them.
    const referenceSearch = catalog.getByRole('textbox', { name: 'Find referenced paths and links', exact: true })
    await catalog.getByRole('button', { name: 'Collapse all', exact: true }).click()
    await referenceSearch.fill('catalog.ts')
    await expect(catalog.locator('[data-reference-path="src/services/catalog.ts"]')).toBeVisible()
    await expect(catalog.locator('[data-reference-path]').filter({ hasText: /\.md$/ })).toHaveCount(0)
    await referenceSearch.fill('')
    await catalog.getByRole('button', { name: 'Expand all', exact: true }).click()
    await capture(page, `${width}-reference-catalog.png`)

    await page.goto(`${origin}/?s=capability&e=capability:browse-catalog`)
    await expect(panel).toBeVisible()
    await expect(references).toHaveCount(0)
    await panel.getByRole('tab', { name: 'References 1', exact: true }).click()
    await expect.poll(() => urlValue(page, 'rt')).toBe('references')
    await expect(references.getByText('src/services/catalog.ts#CatalogService', { exact: true })).toBeVisible()
    await expect(references.getByText('implementation', { exact: true })).toBeVisible()
    await expect(references.getByRole('tree', { name: 'In this repository', exact: true })).toBeVisible()
    const sourceLink = references.getByRole('link', { name: 'src/services/catalog.ts#CatalogService', exact: true })
    await expect(sourceLink).not.toHaveAttribute('target', '_blank')
    const readingUrl = page.url()
    await sourceLink.click()
    const source = panel.locator('[data-source-preview]')
    await expect(source.locator('.highlight')).toContainText('export class CatalogService')
    expect(new URL(urlValue(page, 'f'), origin).searchParams.get('target')).toBe('src/services/catalog.ts#CatalogService')
    await expect(source.locator('script')).toHaveCount(0)
    expect(context.pages()).toHaveLength(1)
    await capture(page, `${width}-source-preview.png`)
    await page.reload()
    await expect(source.locator('.highlight')).toContainText('export class CatalogService')
    await panel.getByRole('button', { name: 'Back to Catalog browsing', exact: true }).click()
    await expect(page).toHaveURL(readingUrl)
    await activeTabFits(panel)
    await panel.getByRole('tab', { name: 'References 1', exact: true }).focus()
    await page.keyboard.press('Home')
    await expect.poll(() => urlValue(page, 'rt')).toBeNull()
    await expect(references).toHaveCount(0)
    await activeTabFits(panel)
    await page.goBack()
    await expect(references).toBeVisible()
    await page.reload()
    await expect(references).toBeVisible()
    await activeTabFits(panel)
    await capture(page, `${width}-resource-references.png`)

    // An empty resource gets no References tab, even at a requested References URL.
    await page.goto(`${origin}/?e=entity:order&rt=references`)
    await expect(panel.getByRole('tab', { name: /^References/ })).toHaveCount(0)
    await expect(panel.getByRole('tab', { name: 'Overview', exact: true })).toHaveAttribute('aria-selected', 'true')

    // A Scenario's attachments remain under its own title, distinct from its parent's.
    await page.goto(`${origin}/?e=capability-scenario:browse-catalog&rt=references`)
    await expect(panel.locator('[data-resource-heading]')).toHaveText('Browse the catalog')
    await expect(panel.getByRole('tab', { name: 'References 2', exact: true })).toHaveAttribute('aria-selected', 'true')
    await expect(references.locator('[data-reference-target]')).toHaveCount(2)
    await expect(references.getByText('src/services/catalog.ts#CatalogService.list', { exact: true })).toBeVisible()
    await expect(references.getByText('src/services/catalog.ts#CatalogService', { exact: true })).toHaveCount(0)
    await references.getByRole('link', { name: 'src/routes/storefront.ts:1-3', exact: true }).press('Enter')
    await expect(panel.locator('[data-source-preview] .highlight')).toHaveCount(3)
    expect(context.pages()).toHaveLength(1)
    await panel.getByRole('button', { name: 'Back to Browse the catalog', exact: true }).click()
    await page.reload()
    await expect(references.locator('[data-reference-target]')).toHaveCount(2)
    await activeTabFits(panel)
    await panel.locator('header a[data-resource-key="capability:browse-catalog"]').click()
    await expect(panel.locator('[data-resource-heading]')).toHaveText('Catalog browsing')
    await panel.getByRole('button', { name: 'Back to Browse the catalog', exact: true }).click()
    await expect(references.locator('[data-reference-target]')).toHaveCount(2)
    await expect.poll(() => urlValue(page, 'rt')).toBe('references')
    await panel.getByRole('tab', { name: /^Scenarios/ }).click()
    await expect(panel.locator('[data-row-key="capability-scenario:browse-catalog"] .blr-summary-toggle')).toHaveAttribute('aria-expanded', 'true')
    await panel.getByRole('tab', { name: 'References 2', exact: true }).click()
    await expect.poll(() => urlValue(page, 'e')).toBe('capability-scenario:browse-catalog')
    await expect(references.locator('[data-reference-target]')).toHaveCount(2)

    // Exercise previews and long reference lists without changing the authored fixture.
    const populated = structuredClone(report)
    populated.references.push({ kind: 'doc', role: 'context', title: 'Product handbook', target: 'https://example.com/handbook' })
    populated.model.entities.find(item => item.id === 'order').references = [
      { kind: 'spec', role: 'intent', title: 'Why an agent harness is an Entity that acts', target: 'spec/format.md' },
      { kind: 'doc', role: 'context', target: 'docs/skills.md' }
    ]
    const resource = populated.model.capabilities.find(item => item.id === 'browse-catalog')
    resource.references[0].title = resource.references[0].target
    resource.references.push({ kind: 'visual', role: 'intent', title: 'Reference preview', target: 'reference-preview.svg' })
    resource.references.push(...Array.from({ length: 30 }, (_, index) => ({ kind: 'spec', role: 'context', title: `Supporting document ${index + 1}`, target: `https://example.com/references/${index + 1}` })))
    await page.route('**/_businesslens/report.json', route => route.fulfill({ json: populated }))
    await page.route('**/_businesslens/file/reference-preview.svg', route => route.fulfill({ contentType: 'image/svg+xml', body: '<svg xmlns="http://www.w3.org/2000/svg" width="320" height="160"><rect width="320" height="160" fill="#bbb"/></svg>' }))
    await page.goto(`${origin}/?e=entity:order&rt=references`)
    const specification = references.locator('[data-reference-target="spec/format.md"]')
    expect(new URL(await specification.getByRole('link', { name: /^spec\/format\.md/ }).getAttribute('href'), origin).searchParams.get('f')).toBe('/_businesslens/file/spec/format.md')
    await expect(specification.locator('[data-reference-label]')).toHaveText('spec/format.md')
    await expect(specification.locator('[data-reference-title]')).toHaveText('Why an agent harness is an Entity that acts')
    await expect(specification.locator('[data-reference-location]')).toHaveCount(0)
    await expect(references.getByText('docs/skills.md', { exact: true })).toHaveCount(1)
    await expect(references.locator('[data-reference-target="docs/skills.md"] [data-reference-location]')).toHaveCount(0)
    await expect(references.locator('[data-reference-target="docs/skills.md"] [data-reference-title]')).toHaveCount(0)
    await capture(page, `${width}-titled-reference-path.png`)
    await page.goto(`${origin}/?t=references`)
    await catalog.getByRole('button', { name: 'Expand all', exact: true }).click()
    await expect(catalog.locator('[data-reference-target]')).toHaveCount(attachmentCount(populated))
    const productReference = catalog.locator('[data-reference-target="https://example.com/handbook"]')
    await expect(productReference).toHaveCount(1)
    // Repository files and external links are separate sections, each counted.
    await expect(catalog.locator('[data-reference-origin="external"] [data-reference-target="https://example.com/handbook"]')).toHaveCount(1)
    await expect(catalog.locator('[data-reference-origin="internal"] [data-reference-target^="https://"]')).toHaveCount(0)
    await expect(catalog.getByRole('region', { name: 'External', exact: true }).locator('[data-reference-target]')).toHaveCount(externalCount(populated))
    await expect(catalog.locator('[data-reference-origin="external"] [data-reference-section-count]')).toContainText(`${externalCount(populated)} citations`)
    // A whole location opens from its row; the external one in a new tab.
    const handbookOpen = catalog.locator('[data-reference-path="https://example.com/handbook"]').locator('xpath=..').locator('[data-reference-open-location]')
    await expect(handbookOpen).toHaveAttribute('target', '_blank')
    await expect(handbookOpen.locator('[data-external-reference]')).toBeVisible()
    await expect(productReference.locator('[data-reference-open]')).toHaveCount(0)
    // An external page is drawn once, under its site, by its authored title.
    await expect(catalog.locator('[data-reference-path="https://example.com/handbook"]')).toHaveText('Product handbook')
    await expect(catalog.locator('[data-reference-path="site:example.com"]')).toHaveText('example.com')
    await expect(productReference.getByText(report.title, { exact: true })).toBeVisible()
    await expect(productReference.locator('[data-resource-key]')).toHaveCount(0)
    // A kind card filters whole citations; its total never changes.
    const visuals = attachments(populated).filter(reference => reference.kind === 'visual').length
    await catalog.locator('[data-reference-summary="visual"]').click()
    await expect(catalog.locator('[data-reference-summary="visual"]')).toHaveAttribute('aria-pressed', 'true')
    await catalog.getByRole('button', { name: 'Expand all', exact: true }).click()
    await expect(catalog.locator('[data-reference-target]')).toHaveCount(visuals)
    await expect(catalog.locator('[data-reference-summary="visual"] [data-reference-summary-count]')).toHaveText(String(visuals))
    await catalog.locator('[data-reference-summary="visual"]').click()
    await catalog.getByRole('button', { name: 'Collapse all', exact: true }).click()
    await expect(catalog.locator('[data-reference-target]')).toHaveCount(0)
    await expect(catalog.locator('img')).toHaveCount(0)
    await page.goto(`${origin}/?e=capability:browse-catalog&rt=references`)
    await expect(panel.getByRole('tab', { name: 'References 32', exact: true })).toHaveAttribute('aria-selected', 'true')
    await expect(references.locator('[data-reference-target]')).toHaveCount(32)
    await expect(references.locator('img')).toHaveCount(0)
    await expect(references.locator('[data-reference-target="src/services/catalog.ts#CatalogService"] [data-reference-location]')).toHaveCount(0)
    await expect(references.locator('[data-reference-target="src/services/catalog.ts#CatalogService"] [data-reference-title]')).toHaveCount(0)
    const codeGroup = references.getByText('Code', { exact: true }).locator('..')
    await codeGroup.focus()
    await page.keyboard.press('ArrowLeft')
    await expect(references.getByText('src/services/catalog.ts#CatalogService', { exact: true })).toHaveCount(0)
    await page.reload()
    await expect(references.getByRole('button', { name: 'Expand Code', exact: true })).toBeVisible()
    await references.getByRole('button', { name: 'Expand Code', exact: true }).click()
    await expect(references.locator('[data-reference-target]')).toHaveCount(32)
    await references.getByText('Visuals', { exact: true }).click()
    await expect(references.getByText('Reference preview', { exact: true })).toHaveCount(0)
    await references.getByText('Visuals', { exact: true }).click()
    await references.getByText('Reference preview', { exact: true }).click()
    await expect(references.locator('img')).toBeVisible()
    await expect(references.getByText('reference-preview.svg', { exact: true })).toHaveCount(1)
    await expect.poll(() => references.locator('img').evaluate(image => image.naturalWidth)).toBe(320)
    await expect(references.getByText('intent', { exact: true })).toBeVisible()
    await expect(references.getByText('context', { exact: true }).first()).toBeVisible()
    const supportingLink = references.getByRole('link', { name: 'Supporting document 1', exact: true })
    await expect(supportingLink).toHaveAttribute('target', '_blank')
    await context.route('https://example.com/references/*', route => route.fulfill({ contentType: 'text/html', body: '<h1>Supporting document</h1>' }))
    const popupReady = page.waitForEvent('popup')
    await supportingLink.locator('../..').press('Enter')
    const popup = await popupReady
    await expect(popup).toHaveURL('https://example.com/references/1')
    await popup.close()
    await page.reload()
    await expect(references.locator('img')).toBeVisible()
    await capture(page, `${width}-reference-preview.png`)
    await references.getByText('Reference preview', { exact: true }).click()
    await references.getByText('Supporting document 30', { exact: true }).scrollIntoViewIfNeeded()
    const top = await panel.locator('[data-resource-scroll]').evaluate(item => item.scrollTop)
    expect(top).toBeGreaterThan(0)
    await panel.getByRole('button', { name: 'Close resource', exact: true }).click()
    await expect.poll(() => urlValue(page, 'e')).toBeNull()
    await page.goBack()
    await expect(references).toBeVisible()
    await expect.poll(() => panel.locator('[data-resource-scroll]').evaluate(item => item.scrollTop)).toBeCloseTo(top, 0)
    await page.reload()
    await expect(references).toBeVisible()
    await expect.poll(() => panel.locator('[data-resource-scroll]').evaluate(item => item.scrollTop)).toBeCloseTo(top, 0)
    await activeTabFits(panel)
    await page.setViewportSize({ width: width === 1440 ? 320 : 1440, height: 900 })
    await activeTabFits(panel)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
    console.log(`Passed ${width}px: reference catalog, owner destinations, counts, ownership, tree grouping/toggles, previews, empty state, Back/reload, keyboard, scroll and resize.`)
    await context.close()
  }
  expect(errors).toEqual([])
} finally { await browser.close() }
