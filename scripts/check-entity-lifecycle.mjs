#!/usr/bin/env node
/** Lifecycle drawings, local inspection and panel expansion preserve the reading. */
import { chromium, expect } from '@playwright/test'
import { mkdirSync } from 'node:fs'
import { join } from 'node:path'
const origin = process.argv[2]
if (!origin) throw new Error('Pass a running fixture-shop report URL.')
const screenshots = process.env.BLR_NAV_SCREENSHOTS
if (screenshots) mkdirSync(screenshots, { recursive: true })
const browser = await chromium.launch()
const errors = []
try {
  for (const [width, height] of [[1440, 1000], [820, 800], [390, 844]]) {
    const context = await browser.newContext({ viewport: { width, height }, reducedMotion: 'reduce' })
    const page = await context.newPage()
    page.setDefaultTimeout(15000)
    page.on('pageerror', error => errors.push(error.message))
    const panel = page.locator('[data-resource-panel]')
    const inspector = panel.locator('[data-lifecycle-inspector]')
    const rows = panel.locator('[data-lifecycle-rows]')
    const viewport = () => panel.locator('.vue-flow__transformationpane').evaluate(element => {
      const matrix = new DOMMatrix(getComputedStyle(element).transform)
      const shell = element.closest('.blr-flow-shell')
      return { zoom: matrix.a, x: (shell.clientWidth / 2 - matrix.e) / matrix.a, y: (shell.clientHeight / 2 - matrix.f) / matrix.a }
    })
    await page.goto(`${origin}/?s=entity&t=graph&e=entity:order`)
    await expect(panel.locator('[data-entity-states]')).toHaveCount(0)
    await expect(panel.getByRole('heading', { name: /Information kept/ })).toBeVisible()
    await panel.getByRole('tab', { name: 'Lifecycle', exact: true }).click()
    await expect(panel.locator('[data-entity-states]')).toHaveCount(0)
    await expect(panel.locator('[data-flow-ready=true]')).toBeVisible()
    await expect(rows).toHaveCount(0)
    await expect(inspector).toHaveCount(0)
    await expect(panel.locator('[data-lifecycle-unplaced]')).toContainText('Changes without specified states · 1')

    const state = panel.locator('.vue-flow__node').getByRole('button', { name: 'Pending', exact: true })
    await state.focus()
    await page.keyboard.press('Enter')
    await expect(inspector.getByRole('heading', { name: 'Pending', exact: true })).toBeFocused()
    await expect(inspector.locator('a[data-resource-key^="capability-scenario:"]')).not.toHaveCount(0)
    await expect(inspector.getByText('Left here by', { exact: true })).toBeVisible()
    await panel.getByRole('tab', { name: 'Overview', exact: true }).click()
    await expect(panel.locator('[data-entity-states]')).toHaveCount(0)
    await panel.getByRole('tab', { name: 'Lifecycle', exact: true }).click()
    await expect(inspector.getByRole('heading', { name: 'Pending', exact: true })).toBeVisible()
    // Reselect after remount so Close has a live focus destination.
    await state.focus()
    await page.keyboard.press('Enter')
    await inspector.getByRole('button', { name: 'Close lifecycle details' }).click()
    await expect(state).toBeFocused()
    await panel.getByRole('button', { name: 'Draw as graph', exact: true }).focus()

    const edge = panel.getByRole('button', { name: 'Inspect Confirmed → Cancelled', exact: true })
    await edge.focus()
    await page.keyboard.press('Enter')
    await expect(inspector.getByRole('heading', { name: 'Confirmed → Cancelled', exact: true })).toBeVisible()
    await expect(inspector.getByRole('heading', { name: 'Who may make this change' })).toBeVisible()
    await expect(inspector.locator('a[data-resource-key="rule:who-may-change-an-order"]')).toBeVisible()
    await expect(inspector.locator('a[data-resource-key^="capability-scenario:"]')).not.toHaveCount(0)
    if (width >= 768) {
      const before = await panel.boundingBox()
      const graphBefore = await viewport()
      await panel.getByRole('button', { name: 'Expand resource', exact: true }).click()
      await expect.poll(async () => Math.round((await panel.boundingBox()).width)).toBe(width)
      await expect.poll(async () => (await viewport()).zoom).toBeCloseTo(graphBefore.zoom, 4)
      await expect.poll(async () => (await viewport()).x).toBeCloseTo(graphBefore.x, 1)
      await expect.poll(async () => (await viewport()).y).toBeCloseTo(graphBefore.y, 1)
      await expect(inspector.getByRole('heading', { name: 'Confirmed → Cancelled', exact: true })).toBeVisible()
      if (width >= 1000) {
        const graphBox = await panel.locator('.blr-lifecycle-diagram').boundingBox()
        const detailBox = await inspector.boundingBox()
        expect(detailBox.x).toBeGreaterThan(graphBox.x + graphBox.width)
      }
      if (screenshots) await page.screenshot({ animations: 'disabled', path: join(screenshots, `${width}-lifecycle-expanded.png`) })
      await page.reload()
      await expect(panel.getByRole('button', { name: 'Restore resource size', exact: true })).toBeVisible()
      await expect(inspector.getByRole('heading', { name: 'Confirmed → Cancelled', exact: true })).toBeVisible()
      await panel.getByRole('button', { name: 'Restore resource size', exact: true }).click()
      await expect.poll(async () => Math.round((await panel.boundingBox()).width)).toBe(Math.round(before.width))
    } else {
      await expect(panel.getByRole('button', { name: 'Expand resource', exact: true })).toHaveCount(0)
    }
    const detailBox = await inspector.boundingBox()
    expect(detailBox.y + detailBox.height).toBeLessThanOrEqual(height)
    if (screenshots) await page.screenshot({ animations: 'disabled', path: join(screenshots, `${width}-lifecycle-inspector.png`) })

    await panel.getByRole('button', { name: 'Draw as rows', exact: true }).click()
    await expect(panel.locator('.blr-lifecycle-diagram')).toHaveCount(0)
    await expect(inspector).toHaveCount(0)
    await expect(rows.locator('[data-lifecycle-group]')).toHaveCount(6)
    await expect(rows.locator('[data-lifecycle-change]')).toHaveCount(6)
    await expect(rows.locator('[data-state="Pending"] [data-lifecycle-change]')).toHaveCount(2)
    await expect(rows.locator('[data-state="Confirmed"] [data-lifecycle-change]')).toHaveCount(2)
    await expect(rows.locator('[data-state="Cancelled"]')).toContainText('No outgoing changes are described in the model.')
    await expect(rows.locator('[data-state="Refunded"]')).toContainText('No outgoing changes are described in the model.')
    await rows.getByRole('button', { name: 'Collapse Confirmed, 2 changes', exact: true }).click()
    await page.reload()
    await expect(rows.getByRole('button', { name: 'Expand Confirmed, 2 changes', exact: true })).toBeVisible()
    await rows.getByRole('button', { name: 'Expand Confirmed, 2 changes', exact: true }).click()
    await expect(rows.getByRole('button', { name: /Confirmed → Cancelled/ })).toHaveAttribute('aria-expanded', 'true')
    await expect(rows.locator('[data-lifecycle-change-details]')).toContainText('Who may change an order')
    await rows.locator('a[data-resource-key="rule:who-may-change-an-order"]').click()
    await expect(panel.locator('[data-resource-heading]')).toContainText('Who may change an order')
    await panel.getByRole('button', { name: 'Back to Order', exact: true }).click()
    await expect(panel.getByRole('button', { name: 'Draw as rows', exact: true })).toHaveAttribute('aria-pressed', 'true')
    await expect(rows.getByRole('button', { name: /Confirmed → Cancelled/ })).toHaveAttribute('aria-expanded', 'true')
    await page.reload()
    await expect(rows.getByRole('button', { name: /Confirmed → Cancelled/ })).toHaveAttribute('aria-expanded', 'true')
    if (screenshots) await page.screenshot({ animations: 'disabled', path: join(screenshots, `${width}-lifecycle-rows.png`) })
    await panel.getByRole('button', { name: 'Expand all', exact: true }).click()
    await expect(rows.locator('[data-lifecycle-change-details]')).toHaveCount(6)
    await panel.getByRole('button', { name: 'Collapse all', exact: true }).click()
    await expect(rows.locator('[data-group-header][aria-expanded="false"]')).toHaveCount(6)
    await expect(rows.locator('[data-lifecycle-change-details]')).toHaveCount(0)
    await panel.getByRole('button', { name: 'Draw as graph', exact: true }).click()
    await expect(panel.locator('[data-flow-ready=true]')).toBeVisible()
    await state.focus()
    await page.keyboard.press('Enter')
    await panel.getByRole('button', { name: 'Draw as rows', exact: true }).click()
    await expect(inspector).toHaveCount(0)
    await expect(rows.getByRole('button', { name: 'Collapse Pending, 2 changes', exact: true })).toBeVisible()
    await expect(rows.getByRole('button', { name: 'Expand Confirmed, 2 changes', exact: true })).toBeVisible()
    await panel.getByRole('button', { name: 'Draw as graph', exact: true }).click()
    await expect(panel.locator('[data-flow-ready=true]')).toBeVisible()
    await panel.locator('[data-lifecycle-unplaced]').getByRole('button', { name: 'Information changed' }).click()
    await expect(inspector).toContainText('This change has no specified states.')
    await expect(inspector.locator('a[data-resource-key="capability:manage-orders"]')).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
    await page.keyboard.press('Escape')
    await expect(panel).toHaveCount(0)
    await expect(page.getByRole('button', { name: 'Draw as graph', exact: true })).toHaveAttribute('aria-pressed', 'true')
    console.log(`Passed ${width}px: States with outgoing changes, empty States, group/child expansion and persistence, keyboard inspection, panel expansion, Graph/Rows selection, linked-resource Back and stateless changes.`)
    await context.close()
  }
  expect(errors).toEqual([])
} finally { await browser.close() }
